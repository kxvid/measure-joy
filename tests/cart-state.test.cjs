/* eslint-disable @typescript-eslint/no-require-imports -- Isolated Node CommonJS test harness. */
const test = require('node:test')
const assert = require('node:assert/strict')
const load = require('./helpers/load-typescript.cjs')()
const { parseStoredCart, boundedQuantity, reconcileCart, cartIssues } = load('lib/cart-state.ts')
const product = (changes = {}) => ({ id: 'prod_Camera', name: 'Canon camera', description: 'Tested', priceInCents: 12000, images: ['https://example.com/camera.jpg'], category: 'camera', condition: 'Good', specs: {}, inStock: true, stockCount: 3, ...changes })
test('malformed browser storage cannot create a checkout item or crash bag restoration', () => {
  for (const raw of ['{', '{}', 'null', '[null]', JSON.stringify([{ product: product(), quantity: '2' }]), JSON.stringify([{ product: product({ priceInCents: -1 }), quantity: 1 }])]) assert.equal(parseStoredCart(raw).length, 0)
  const restored = parseStoredCart(JSON.stringify([{ product: product(), quantity: 2 }, { product: {}, quantity: 1 }]))
  assert.equal(restored.length, 1)
  assert.equal(restored[0].quantity, 2)
})
test('restoring duplicate entries preserves the requested amount so stock issues remain visible', () => {
  const restored = parseStoredCart(JSON.stringify([{ product: product(), quantity: 2 }, { product: product(), quantity: 2 }]))
  assert.equal(restored.length, 1)
  assert.equal(restored[0].quantity, 4)
  assert.equal(cartIssues(restored).length, 1)
})
test('quantity controls cannot create fractional, negative, unavailable, or excessive stock quantities', () => {
  for (const quantity of [0, -1, 1.5, Infinity, NaN]) assert.equal(boundedQuantity(product(), quantity), 0)
  assert.equal(boundedQuantity(product(), 5), 3)
  assert.equal(boundedQuantity(product({ stockCount: 0 }), 1), 0)
  assert.equal(boundedQuantity(product({ inStock: false }), 1), 0)
  assert.equal(boundedQuantity(product({ stockCount: NaN }), 1), 0)
})
test('catalog reconciliation replaces stale prices and blocks missing products without silently deleting the bag', () => {
  const result = reconcileCart([{ product: product(), quantity: 2 }, { product: product({ id: 'prod_Missing' }), quantity: 1 }], [product({ priceInCents: 13000, stockCount: 1 })])
  assert.equal(result.changedPrices, true)
  assert.equal(result.items[0].product.priceInCents, 13000)
  assert.equal(result.items[0].quantity, 2)
  assert.equal(result.items[1].product.name, 'Canon camera')
  assert.equal(result.items[1].product.inStock, false)
  assert.equal(result.issues.length, 2)
})
